    private void closeComplete(boolean wasAnimated) {
        mIsOpen = false;
        // CaretLauncher: whether the folder had the focus, for shouldFocusIconOnClose.
        boolean hadFocus = hasFocus();

        // TODO: Clear all active animations.
        BaseDragLayer parent = (BaseDragLayer) getParent();
        if (parent != null) {
            parent.removeView(this);
        }
        mActivityContext.getDragController().removeDropTarget(this);
        clearFocus();
        if (mFolderIcon != null) {
            mFolderIcon.setVisibility(View.VISIBLE);
            mFolderIcon.setIconVisible(true);
            // CaretLauncher: folder icons have no name.
            if (wasAnimated) {
                mFolderIcon.animateBgShadowAndStroke();
                mFolderIcon.onFolderClose(mContent.getCurrentPage());
                if (mFolderIcon.hasDot()) {
                    mFolderIcon.animateDotScale(0f, 1f);
                }
                // CaretLauncher: the app decides (shouldFocusIconOnClose).
                if (shouldFocusIconOnClose(hadFocus)) mFolderIcon.requestFocus();
            }
        }

        if (mRearrangeOnClose) {
            rearrangeChildren();
            mRearrangeOnClose = false;
        }
        if (getItemCount() <= 1) {
            if (!mIsDragInProgress && !mSuppressFolderDeletion) {
                replaceFolderWithFinalItem();
            } else if (mIsDragInProgress) {
                mDeleteFolderOnDropCompleted = true;
            }
        } else if (!mIsDragInProgress) {
            mContent.unbindItems();
        }
        mSuppressFolderDeletion = false;
        clearDragInfo();
        setState(STATE_CLOSED);
        mContent.setCurrentPage(0);

        if (Flags.enableExpressiveFolderExpansion()) {
            FolderAnimationSpringBuilderManager.resetLauncherScale(mLauncherDelegate);
            FolderAnimationSpringBuilderManager.resetScrimAndZoom(mLauncherDelegate);
        }
    }

