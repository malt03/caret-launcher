    @Override
    public void onDrop(DragObject d, DragOptions options) {
        // If the icon was dropped while the page was being scrolled, we need to compute
        // the target location again such that the icon is placed of the final page.
        if (!mContent.rankOnCurrentPage(mEmptyCellRank)) {
            // Reorder again.
            mTargetRank = getTargetRank(d, null);

            // Rearrange items immediately.
            mReorderAlarmListener.onAlarm(mReorderAlarm);

            // TextLauncher: no scroll hint or scroll pause alarms (one page).
        }
        mContent.completePendingPageChanges();
        Launcher launcher = mLauncherDelegate.getLauncher();
        if (launcher == null) {
            return;
        }

        // TextLauncher: no shortcuts that go through their configuration activity
        // (PendingAddShortcutInfo), and no WorkspaceItemFactory to copy (every drag carries a
        // WorkspaceItemInfo), so only the branch that drops the dragged item is left. The block
        // keeps that branch's indentation.
        {
            final ItemInfo si;
            {
                // WorkspaceItemInfo or AppPairInfo
                si = d.dragInfo;
            }

            View currentDragView;
            if (mIsExternalDrag) {
                currentDragView = mContent.createAndAddViewForRank(si, mEmptyCellRank);

                // TextLauncher: no database write (addOrMoveItemInDatabase); the icon tells the
                // app, which saves its model (addFolderContent below).
                mIsExternalDrag = false;
            } else {
                currentDragView = mCurrentDragView;
                mContent.addViewForRank(currentDragView, si, mEmptyCellRank);
            }

            if (d.dragView.hasDrawn()) {
                // Temporarily reset the scale such that the animation target gets calculated
                // correctly.
                float scaleX = getScaleX();
                float scaleY = getScaleY();
                setScaleX(1.0f);
                setScaleY(1.0f);
                launcher.getDragLayer().animateViewIntoPosition(d.dragView, currentDragView, null);
                setScaleX(scaleX);
                setScaleY(scaleY);
            } else {
                d.deferDragViewCleanupPostAnimation = false;
                currentDragView.setVisibility(VISIBLE);
            }

            mItemsInvalidated = true;
            rearrangeChildren();

            // Temporarily suppress the listener, as we did all the work already here.
            executeWithContentUpdateSuppressed(() -> addFolderContent(si, mEmptyCellRank, false));

            // TextLauncher: no database writes (updateItemLocationsInDatabaseBatch).
        }

        // Clear the drag info, as it is no longer being dragged.
        mIsDragInProgress = false;

        // TextLauncher: one page, so no multi-page animation flag; the home screen leaves its
        // spring-loaded state as the drag ends (SpringLoadedListener), and there are no drag
        // announcements or logs.
    }

    // This is used so the item doesn't immediately appear in the folder when added. In one case
